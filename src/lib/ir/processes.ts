export function procsFor(scenarioId: ScenarioId, hostMode: HostMode): HostProc[] {
  const base = hostMode === "physical" ? PHYSICAL_BASE : LAB_BASE;
  const extra = SCENARIO_PROCS[scenarioId];
  const merged = [...base, ...extra];
  const seen = new Set<number>();
  const out: HostProc[] = [];
  for (const p of merged) {
    if (p.physicalOnly && hostMode !== "physical") continue;
    if (seen.has(p.pid)) continue;
    seen.add(p.pid);
    out.push(p);
  }
  return out.sort((a, b) => a.pid - b.pid);
}

export function seedProcState(scenarioId: ScenarioId, hostMode: HostMode): ProcState[] {
  return procsFor(scenarioId, hostMode).map((p) => ({ pid: p.pid, status: "running" as const }));
}

export function procActionFinding(proc: HostProc, scenarioId: ScenarioId): Finding {
  if (proc.findingId && !proc.findingId.startsWith("phys-vol-")) {
    return {
      id: proc.findingId,
      scenarioId,
      kind: "process",
      severity: proc.benign ? "low" : "high",
      title: proc.name,
      subject: proc.name,
      path: proc.path,
      pid: proc.pid,
      owner: proc.user,
      reason: "",
      evidence: [],
      engines: ["resident"],
      sources: ["core"],
      tactics: [],
      action: "terminate",
      actionHint: "结束该进程。",
    };
  }
  return {
    id: `proc-act-${proc.pid}`,
    scenarioId,
    kind: "process",
    severity: proc.benign ? "low" : "high",
    title: `结束 ${proc.name}`,
    subject: proc.name,
    path: proc.path,
    pid: proc.pid,
    owner: proc.user,
    reason: proc.benign
      ? "从会话进程表手动结束。浏览器只能改本控制台的进程表，不能向内核发出 NtTerminateProcess。"
      : "会话表中的可疑进程，结束并阻断该映像再次执行。",
    evidence: [`PID ${proc.pid}`, proc.path, `父进程 ${proc.parentPid}`],
    engines: ["resident"],
    sources: ["core"],
    tactics: proc.benign ? [] : ["T1055"],
    action: "terminate",
    actionHint: "从会话进程表结束该 PID。",
  };
}
