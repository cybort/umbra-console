const NODES_BY_SCENARIO: Record<ScenarioId, string[]> = {
  rat: ["proc-svchost", "mem-explorer-rx", "proc-explorer", "proc-rundll"],
  miner: ["proc-winupdate", "mem-wu-rwx", "proc-watch"],
  hijack: ["proc-sync", "mem-lsass", "proc-lsass"],
  clean: ["proc-it-explorer", "proc-print"],
};

export function nodesFor(scenarioId: ScenarioId) {
  const ids = new Set(NODES_BY_SCENARIO[scenarioId]);
  return GRAPH_NODES.filter((n) => ids.has(n.id));
}

export function edgesFor(scenarioId: ScenarioId) {
  return GRAPH_EDGES.filter((e) => e.scenarioId === scenarioId).sort((a, b) => a.seq - b.seq);
}

